"""B-2 / B-4, step 2: exact kernel systems of Lemma K for every convention; generic ranks and kernels on strata.

For each model the coefficient matrix Mmat(theta) (Lemma K) is built; its rank is computed
 (1) at a random rational point (generic rank),
 (2) symbolically on each candidate stratum (remaining parameters symbolic, generic on the stratum),
and the kernel is printed. The matrices are written to b2_02_matrices.wl for the independent semi-algebraic decision of the
degenerate sets (b2_03w_reduce.wl, Wolfram Engine).
Output: b2_02_kernel_system_run.out (text) and b2_02_matrices.wl.
"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sympy as sp  # noqa: E402
from kernel_system import (model, matrix, xi, b, bs, tR, tl, R, eps, eps0, tn_s, to_s)  # noqa: E402

t = sp.Symbol("t", positive=True)
HERE = os.path.dirname(os.path.abspath(__file__))
lines = []


def log(*a):
    s = " ".join(str(x) for x in a)
    print(s)
    lines.append(s)


RAND = {xi: sp.Rational(7, 10), b: sp.Rational(23, 10), bs: 1, tR: sp.Rational(3, 10), tl: sp.Rational(1, 8),
        R: sp.Rational(2, 5), eps: sp.Rational(3, 7), eps0: sp.Rational(5, 11), tn_s: sp.Rational(1, 5),
        to_s: sp.Rational(2, 9)}

MODELS = {
    # bare film, temperature T read at the heated face (the twin's observable)
    "T_local_Rknown": model("T", "local", False),
    "T_local_Runknown": model("T", "local", True),
    "T_eps_Rknown": model("T", "eps", False),
    "T_eps_Runknown": model("T", "eps", True),
    "T_free_Rknown": model("T", "free", False),
    "T_free_Runknown": model("T", "free", True),
    # bare film, entropic temperature theta_e = (1 + tau_l p) T read at the heated face (twin option)
    "thetae_local_Rknown": model("theta_e", "local", False),
    "thetae_local_Runknown": model("theta_e", "local", True),
    "thetae_eps_Rknown": model("theta_e", "eps", False),
    "thetae_eps_Runknown": model("theta_e", "eps", True),
    # theta-quadrupole: theta-jumps at both faces with the same coefficient (film block of the transducer stack)
    "thq_eps_Rknown": model("theta_q", "eps", False),
    "thq_eps_Runknown": model("theta_q", "eps", True),
    "thq_free_Runknown": model("theta_q", "free", True),
    # different conventions at the two faces (top coefficient eps0 tau_l, bottom eps tau_l)
    "eps0_eps_Runknown": model("eps0", "eps", True),
}

STRATA = {
    "generic": {},
    "Delta": {tR: t, tl: t},
    "Delta,R=0": {tR: t, tl: t, R: 0},
    "Delta,b=bs": {tR: t, tl: t, b: bs},
    "Delta,b=bs,R=0": {tR: t, tl: t, b: bs, R: 0},
    "Fourier corner": {tR: 0, tl: 0},
    "Fourier corner,R=0": {tR: 0, tl: 0, R: 0},
    "Fourier corner,R=0,b=bs": {tR: 0, tl: 0, R: 0, b: bs},
    "tl=0": {tl: 0},
    "tl=0,R=0": {tl: 0, R: 0},
    "tR=0": {tR: 0},
    "tR=0,R=0": {tR: 0, R: 0},
    "b=bs": {b: bs},
    "b=bs,R=0": {b: bs, R: 0},
    "R=0": {R: 0},
}

minors_out = {}
for name, m in MODELS.items():
    Mm = matrix(m)
    n = Mm.shape[1]
    log("=" * 100)
    log(f"MODEL {name}: obs={m['obs']} iface={m['iface']} R_unknown={m['R_unknown']} components={m['names']}")
    log(f"  Mmat shape {Mm.shape}")
    Mr = Mm.subs(RAND)
    log(f"  generic rank (random rational point): {Mr.rank()} of {n}")
    for sname, sub in STRATA.items():
        Ms = Mm.subs(sub).applyfunc(sp.expand)
        rk = Ms.rank(simplify=True)
        line = f"  stratum {sname:28s}: rank {rk} of {n}"
        if rk < n:
            ker = Ms.nullspace(simplify=True)
            ker = [list(sp.simplify(v.T)) for v in ker]
            line += f"   kernel {ker}"
        log(line)
    minors_out[name] = Mm.subs(bs, 1)

with open(os.path.join(HERE, "b2_02_kernel_system_run.out"), "w") as fh:
    fh.write("\n".join(lines) + "\n")

# Wolfram export of the matrices with b_s = 1 (scale invariance)
_REN = {xi: sp.Symbol("xi"), b: sp.Symbol("b"), tR: sp.Symbol("tR"), tl: sp.Symbol("tl"), R: sp.Symbol("R"),
        eps: sp.Symbol("eps"), eps0: sp.Symbol("epsz"), tn_s: sp.Symbol("tn"), to_s: sp.Symbol("to")}


def wl(expr):
    return sp.printing.mathematica.mathematica_code(sp.sympify(expr).subs(_REN))


with open(os.path.join(HERE, "b2_02_matrices.wl"), "w") as fh:
    fh.write("(* coefficient matrices Mmat of Lemma K, b_s = 1; generated by b2_02_kernel_system_run.py *)\n")
    fh.write("mats = <|\n")
    items = []
    for name, Mm in minors_out.items():
        rows = ["{" + ", ".join(wl(e) for e in Mm.row(i)) + "}" for i in range(Mm.shape[0])]
        items.append(f'  "{name}" -> {{' + ", ".join(rows) + "}")
    fh.write(",\n".join(items) + "\n|>;\n")
print("written", os.path.join(HERE, "b2_02_matrices.wl"))
